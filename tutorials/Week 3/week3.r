Basic Data & Sample Variables
• x or X: An individual data value or observation in a set.
• n: The number of observations in a sample (sample size).
• N: The total number of observations in a population (population size).
• \(\sum \) (Sigma): Summation; tells you to add up all the values in a given set.
Mean (Averages)
• x̄ ("x-bar"): The arithmetic mean of a sample (\(\bar{x} = \frac{\sum x}{n}\)).
• μ ("mu"): The mean of an entire population (\(\mu = \frac{\sum X}{N}\)).
Spread and Dispersion
• s: The standard deviation of a sample.
• σ ("sigma"): The standard deviation of a population.
• s²: The variance of a sample.
• σ²: The variance of a population.
• IQR: Interquartile range (Q₃ - Q₁), measuring the middle 50% spread.
Probability & Hypothesis Testing
• p: Probability of success, or a p-value in significance testing.
• z: Standard score (z-score), showing how many standard deviations a value is from the mean.
• t: Test statistic used in a t-test when sample sizes are smaller.
• H₀: The null hypothesis.
• \(H_{a}\) or H₁: The alternative hypothesis.
• α ("alpha"): Significance level (threshold for rejecting the null hypothesis).
• df: Degrees of freedom (n - 1 in basic tests).
Regression & Correlation
• r: Sample correlation coefficient measuring linear association.
• ŷ ("y-hat"): The predicted value of the dependent variable y.
• b₀: The y-intercept in a regression line.
• b₁: The slope in a regression line.